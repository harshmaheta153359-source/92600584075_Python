# Mutable and Immutable Objects

# Mutable object - List
list1 = [10, 20, 30]
print("Original List:", list1)

list1[0] = 100
print("Modified List:", list1)


# Immutable object - Tuple
tuple1 = (10, 20, 30)
print("Original Tuple:", tuple1)

print("Tuple is immutable and cannot be changed.")
