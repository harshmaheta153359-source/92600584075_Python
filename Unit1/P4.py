#4 Write a program to demonstrate string 
#operations including slicing formatting and 
#built-in string functions.

string = input("Pass a String: ")
print("String is in uppercase :",string.upper())
print("String in lower :",string.lower())
print("String slicing :",string[0:2])
print(string.title())
print("Is any string present ?",string.isalpha())
print(string.count('string'))
print("String endswith : ",string.endswith('n'))




