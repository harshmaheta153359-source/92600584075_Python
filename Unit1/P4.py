string = 'Python'

print("String in uppercase:", string.upper())
print("String in lowercase:", string.lower())
print("String slicing:", string[0:2])
print("String in title case:", string.title())
print("Is the string alphabetic?:", string.isalpha())
print("Count of 'string':", string.count("string"))
print("Does the string end with 'n'?:", string.endswith("n"))


