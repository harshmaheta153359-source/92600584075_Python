marks = int(input("Enter marks : "))

if marks >= 90:
    print("Grade: A")
elif marks >= 75:
    print("Grade: B")
elif marks >= 50:
    print("Grade: C")
else:
    print("Grade: D")

number = int(input("Enter number : "))

if number % 2 == 0:
    print("Number is Even")
else:
    print("Number is Odd")
